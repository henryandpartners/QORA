// ── Interactive distribution chart (canvas) ────────────────────
function buildDistChart(container, data) {
  const states = Object.keys(data.counts);
  const sorted = states.sort((a, b) => data.counts[b] - data.counts[a]);
  const counts = sorted.map(s => data.counts[s]);
  const maxC = Math.max(...counts);
  const uniform = data.shots / 64;

  container.innerHTML = `
    <div class="qora-section-label">MEASUREMENT DISTRIBUTION — HOVER THE STATES</div>
    <div class="qora-chart-wrap">
      <canvas id="qora-dist-canvas"></canvas>
      <div class="qora-chart-tip" id="qora-dist-tip"></div>
    </div>
    <div class="qora-chart-legend">
      <span><i style="background:#00d4ff"></i>above uniform</span>
      <span><i style="background:#ff6b9d"></i>below uniform</span>
      <span><i style="background:#a855f7"></i>most frequent</span>
      <span><i style="background:#fbbf24"></i>uniform 1/64</span>
    </div>
  `;

  const canvas = document.getElementById('qora-dist-canvas');
  const tip = document.getElementById('qora-dist-tip');
  const wrap = canvas.parentElement;
  const W = wrap.clientWidth, H = 240;
  canvas.width = W * 2; canvas.height = H * 2;
  canvas.style.width = W + 'px'; canvas.style.height = H + 'px';
  const c = canvas.getContext('2d');
  c.scale(2, 2);

  const bw = W / 64;
  let progress = 0;
  const t0 = performance.now();

  function draw(hoverIdx = -1) {
    c.clearRect(0, 0, W, H);
    const base = H - 18;
    for (let i = 0; i < 64; i++) {
      const h = (counts[i] / maxC) * (base - 14) * progress;
      let color = counts[i] > uniform ? '#00d4ff' : '#ff6b9d';
      if (i === 0) color = '#a855f7';
      if (i === hoverIdx) color = '#ffffff';
      c.fillStyle = color;
      c.globalAlpha = hoverIdx === i ? 1 : 0.75;
      c.fillRect(i * bw + 1, base - h, bw - 2, h);
    }
    c.globalAlpha = 1;
    // uniform line
    const uy = base - (uniform / maxC) * (base - 14);
    c.strokeStyle = '#fbbf24';
    c.setLineDash([5, 4]);
    c.beginPath(); c.moveTo(0, uy); c.lineTo(W, uy); c.stroke();
    c.setLineDash([]);
    // baseline
    c.strokeStyle = 'rgba(255,255,255,0.15)';
    c.beginPath(); c.moveTo(0, base + 0.5); c.lineTo(W, base + 0.5); c.stroke();
  }

  function anim() {
    const t = (performance.now() - t0) / 900;
    progress = Math.min(1, 1 - Math.pow(1 - t, 3));
    draw();
    if (progress < 1) requestAnimationFrame(anim);
  }
  anim();

  canvas.addEventListener('mousemove', (e) => {
    const rect = canvas.getBoundingClientRect();
    const idx = Math.floor((e.clientX - rect.left) / bw);
    if (idx < 0 || idx > 63) return;
    draw(idx);
    const s = sorted[idx];
    tip.style.display = 'block';
    tip.textContent = `|${s}⟩  ·  ${counts[s]}×  ·  p = ${(counts[s] / data.shots * 100).toFixed(2)}%`;
    const x = Math.min(Math.max(idx * bw + bw / 2, 70), W - 70);
    tip.style.left = x + 'px';
  });
  canvas.addEventListener('mouseleave', () => {
    tip.style.display = 'none';
    draw();
  });
}

// ── Interactive Hilbert geometry chart (canvas, animated) ──────
function buildHilbertChart(container, data) {
  const states = Object.keys(data.counts);
  const counts = states.map(s => data.counts[s]);
  const amps = counts.map(v => Math.sqrt(v / data.shots));
  const maxAmp = Math.max(...amps);
  const EXAG = 4; // angle exaggeration for visibility

  container.innerHTML = `
    <div class="qora-section-label">GEOMETRY IN C⁶⁴ — HILBERT SPACE (angle ×${EXAG})</div>
    <div class="qora-chart-wrap qora-hilbert">
      <canvas id="qora-hilb-canvas"></canvas>
    </div>
    <div class="qora-chart-legend">
      <span><i style="background:#fbbf24"></i>ideal |U⟩ uniform</span>
      <span><i style="background:#ff6b9d"></i>measured |ψ⟩</span>
      <span><i style="background:#a855f7"></i>d(ψ,U) = ${data.fs_distance_deg.toFixed(2)}°</span>
    </div>
  `;

  const canvas = document.getElementById('qora-hilb-canvas');
  const wrap = canvas.parentElement;
  const W = wrap.clientWidth, H = 320;
  canvas.width = W * 2; canvas.height = H * 2;
  canvas.style.width = W + 'px'; canvas.style.height = H + 'px';
  const c = canvas.getContext('2d');
  c.scale(2, 2);

  const cx = W * 0.38, cy = H / 2, R = Math.min(H, W * 0.7) / 2 - 24;
  const theta = Math.min(data.fs_distance_rad * EXAG, Math.PI / 2.5);
  const rPsi = data.overlap;

  function frame(now) {
    c.clearRect(0, 0, W, H);
    const t = now / 1000;

    // grid rings
    c.strokeStyle = 'rgba(255,255,255,0.07)';
    for (let r = R / 4; r <= R; r += R / 4) {
      c.beginPath(); c.arc(cx, cy, r, 0, Math.PI * 2); c.stroke();
    }

    // 64 amplitude points, slowly rotating, shimmering
    for (let i = 0; i < 64; i++) {
      const ang = (i / 64) * Math.PI * 2 + t * 0.05;
      const rr = (amps[i] / maxAmp) * R;
      const shim = 0.35 + 0.35 * Math.sin(t * 1.4 + i * 0.7);
      c.fillStyle = `rgba(0,212,255,${shim})`;
      c.beginPath();
      c.arc(cx + Math.cos(ang) * rr, cy - Math.sin(ang) * rr, 2, 0, Math.PI * 2);
      c.fill();
    }

    // ideal arrow |U>
    arrow(c, cx, cy, Math.cos(0) * R, -Math.sin(0) * R, '#fbbf24');

    // measured arrow |psi> at theta
    const px = Math.cos(theta) * rPsi * R;
    const py = -Math.sin(theta) * rPsi * R;
    arrow(c, cx, cy, px, py, '#ff6b9d');

    // FS arc + label
    c.strokeStyle = '#a855f7';
    c.lineWidth = 2;
    c.beginPath(); c.arc(cx, cy, R * 0.32, -theta, 0); c.stroke();
    c.lineWidth = 1;
    c.fillStyle = '#a855f7';
    c.font = '11px "Space Mono", monospace';
    c.fillText(`θ = ${data.fs_distance_deg.toFixed(2)}°`, cx + R * 0.36, cy - 6);

    // labels
    c.fillStyle = '#fbbf24';
    c.fillText('|U⟩', cx + R + 8, cy + 4);
    c.fillStyle = '#ff6b9d';
    c.fillText('|ψ⟩', cx + px + (px >= 0 ? 8 : -26), cy + py - 6);

    // side metrics
    c.fillStyle = 'rgba(255,255,255,0.45)';
    c.font = '10px "Space Mono", monospace';
    const lines = [
      `⟨ψ|U⟩   = ${data.overlap.toFixed(4)}`,
      `d(ψ,U)  = ${data.fs_distance_rad.toFixed(4)} rad`,
      `⟨|a|⟩   = ${data.mean_amplitude.toFixed(4)}`,
      `1/√64   = ${data.ideal_amplitude.toFixed(4)}`,
      `H       = ${data.entropy.toFixed(3)} bits`,
    ];
    lines.forEach((l, i) => c.fillText(l, W * 0.72, 40 + i * 20));

    vizRAF = requestAnimationFrame(frame);
  }
  vizRAF = requestAnimationFrame(frame);
}

function arrow(c, x0, y0, dx, dy, color) {
  const x1 = x0 + dx, y1 = y0 + dy;
  c.strokeStyle = color;
  c.lineWidth = 2.5;
  c.beginPath(); c.moveTo(x0, y0); c.lineTo(x1, y1); c.stroke();
  const a = Math.atan2(dy, dx);
  c.fillStyle = color;
  c.beginPath();
  c.moveTo(x1, y1);
  c.lineTo(x1 - 10 * Math.cos(a - 0.4), y1 - 10 * Math.sin(a - 0.4));
  c.lineTo(x1 - 10 * Math.cos(a + 0.4), y1 - 10 * Math.sin(a + 0.4));
  c.closePath(); c.fill();
  c.lineWidth = 1;
}

function stopViz() {
  if (vizRAF) { cancelAnimationFrame(vizRAF); vizRAF = null; }
}


// ── Helpers ────────────────────────────────────────────────────
function hammingWeight(s) {
  let w = 0;
  for (const c of s) if (c === '1') w++;
  return w;
}

function isPalindrome(s) {
  return s === s.split('').reverse().join('');
}

function cryptoRand() {
  const buf = new Uint32Array(1);
  crypto.getRandomValues(buf);
  return buf[0] / 2 ** 32;
}

/** Cryptographically secure weighted sample from the real measurement counts. */
function sampleFromOracle(counts) {
  const states = Object.keys(counts);
  const weights = states.map(s => counts[s]);
  const total = weights.reduce((a, b) => a + b, 0);
  const r = cryptoRand() * total;
  let acc = 0;
  for (let i = 0; i < states.length; i++) {
    acc += weights[i];
    if (r < acc) return states[i];
  }
  return states[states.length - 1];
}

/** Rank of a state by measured frequency (1 = most frequent). */
function rankOf(state, counts) {
  const c = counts[state] || 0;
  return 1 + Object.values(counts).filter(v => v > c).length;
}

function freshness(timestamp) {
  const then = new Date(timestamp).getTime();
  const hrs = Math.max(0, (Date.now() - then) / 3600000);
  if (hrs < 1) return `${Math.round(hrs * 60)} min ago`;
  if (hrs < 48) return `${Math.round(hrs)} h ago`;
  return `${Math.round(hrs / 24)} days ago`;
}


function composeReading(state, data) {
  const count = data.counts[state] || 0;
  const p = count / data.shots;
  const detail = {
    state, count, p, shots: data.shots,
    avg_mi: data.avg_mi, entropy: data.entropy,
    rank: rankOf(state, data.counts),
  };
  const weight = hammingWeight(state);

  if (data.top_states.length && state === data.top_states[0].state) {
    return TOP_STATE_READING(state, detail);
  }
  if (isPalindrome(state)) {
    return PALINDROME_READING(state, detail);
  }
  const variants = READINGS[weight] || READINGS[3];
  const v = cryptoRand() < 0.5 ? 0 : 1;
  return variants[v](state, detail);
}

